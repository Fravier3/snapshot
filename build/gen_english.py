"""Genera src/FranCapture.Core/Localization/English.cs a partir de build/english.tsv (español<TAB>inglés)."""
import io
def esc(s): return s.replace('\\n', '\n').replace('\\\\', '\\').replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
seen = {}; out = []
for line in io.open('build/english.tsv', encoding='utf-8'):
    line = line.rstrip('\n')
    if not line.strip() or '\t' not in line: continue
    es, en = line.split('\t', 1)
    if es in seen: continue
    seen[es] = en
    out.append(f'        ["{esc(es)}"] = "{esc(en)}",')
src = ('// <auto-generated> Generado por build/gen_english.py a partir de build/english.tsv. No editar a mano. </auto-generated>\n'
       'namespace FranCapture.Core.Localization;\n\npublic static partial class English\n{\n    public static readonly Dictionary<string, string> Map = new()\n    {\n'
       + '\n'.join(out) + '\n    };\n}\n')
io.open('src/FranCapture.Core/Localization/English.cs', 'w', encoding='utf-8').write(src)
print(len(out), 'traducciones')
